/**
 * Typed Kotlin facade over the JS `CrispClient` object defined by `CrispClient.generatedJS()` (`client` module).
 * All suspend methods must be called from the main thread (they touch the `WebView`).
 *
 * The Swift counterpart is generated by `mise run codegen`; this one is written by hand, one
 * line per method, following the same recipe: JSON-encode the arguments, call, decode the result.
 */
internal class CrispClientBridge(private val evaluator: JSEvaluator, val events: JSEventBus) {
    private fun caller(function: String) = JSCaller("$JS_CLASS_NAME.$function", evaluator)

    // region Calls

    suspend fun injectMessage(message: Message): Unit = caller("injectMessage")(jsEncode(message))

    suspend fun focusOnForeground(): Unit = caller("focusOnForeground")()

    suspend fun registerNotification(deviceToken: String): Unit =
        caller("registerNotification")(jsEncode(deviceToken))

    suspend fun unregisterNotification(deviceToken: String): Unit =
        caller("unregisterNotification")(jsEncode(deviceToken))

    suspend fun connectSocket(): Unit = caller("connectSocket")()

    suspend fun disconnectSocket(): Unit = caller("disconnectSocket")()

    suspend fun helpdeskArticleOpen(
        locale: LanguageCode,
        slug: String,
        title: String?,
        category: String?,
    ): Unit = caller("helpdeskArticleOpen")(
        jsEncode(locale),
        jsEncode(slug),
        jsEncode(title),
        jsEncode(category),
    )

    suspend fun helpdeskSearch(): Unit = caller("helpdeskSearch")()

    suspend fun chatShow(): Unit = caller("chatShow")()

    suspend fun botScenarioRun(id: BotScenarioId): Unit = caller("botScenarioRun")(jsEncode(id))

    suspend fun getSessionIdentifier(): SessionId = caller("getSessionIdentifier")()

    suspend fun isSessionOngoing(): Boolean = caller("isSessionOngoing")()

    suspend fun messageShow(
        type: ConversationMessageType,
        content: ConversationMessageContent,
        fingerprint: MessageFingerprint?,
        prepend: Boolean?,
    ): Unit = caller("messageShow")(
        jsEncode(type),
        jsEncode(GenericMessageCodec.encodeContent(content)),
        jsEncode(fingerprint),
        jsEncode(prepend),
    )

    suspend fun getMessages(): List<LocalMessage> = caller("getMessages")()

    suspend fun setSessionData(data: List<Tuple>): Unit =
        caller("setSessionData")(jsEncode<JsonElement>(JsonArray(data.map { it.toJson() })))

    suspend fun getSessionData(key: String?): JsonElement = caller("getSessionData")(jsEncode(key))

    suspend fun setSessionSegments(segments: List<String>, overwrite: Boolean?): Unit =
        caller("setSessionSegments")(jsEncode(segments), jsEncode(overwrite))

    suspend fun setSessionEvent(
        name: String,
        data: Map<String, JsonElement>?,
        color: SessionEventColor?,
    ): Unit = caller("setSessionEvent")(
        jsEncode(name),
        jsEncode<JsonElement?>(data?.let(::JsonObject)),
        jsEncode(color),
    )

    suspend fun setUserEmail(email: String, signature: String? = null): Unit =
        caller("setUserEmail")(jsEncode(email), jsEncode(signature))

    suspend fun getUserEmail(): String? = caller("getUserEmail")()

    suspend fun setUserPhone(phone: String): Unit = caller("setUserPhone")(jsEncode(phone))

    suspend fun getUserPhone(): String? = caller("getUserPhone")()

    suspend fun setUserNickname(nickname: String): Unit =
        caller("setUserNickname")(jsEncode(nickname))

    suspend fun getUserNickname(): String? = caller("getUserNickname")()

    suspend fun setUserAvatar(url: String): Unit = caller("setUserAvatar")(jsEncode(url))

    suspend fun getUserAvatar(): String? = caller("getUserAvatar")()

    suspend fun setUserCompany(name: String, company: Company?): Unit =
        caller("setUserCompany")(jsEncode(name), jsEncode(company))

    suspend fun getUserCompany(): Company? = caller("getUserCompany")()

    suspend fun reset(): Unit = caller("reset")()

    // endregion

    // region Events (JS → native). Each registers a handler on the matching channel.

    fun onInterfaceLifecycle(handler: (InterfaceLifecycleEvent) -> Unit) =
        events.register("onInterfaceLifecycle", handler)

    fun onInterfaceAction(handler: (InterfaceActionEvent) -> Unit) =
        events.register("onInterfaceAction", handler)

    fun onMessageSent(handler: (Message) -> Unit) = events.register("onMessageSent", handler)

    fun onMessageReceived(handler: (Message) -> Unit) =
        events.register("onMessageReceived", handler)

    // Hand-written JS (index.html) events.
    internal fun onPickerClick(handler: (PickerClickEvent) -> Unit) =
        events.register("onPickerClick", handler)

    internal fun onLog(handler: (LogEvent) -> Unit) = events.register("onLog", handler)

    internal fun onScriptError(handler: (ScriptErrorEvent) -> Unit) =
        events.register("onScriptError", handler)

    // endregion

    companion object {
        internal const val JS_CLASS_NAME = "CrispClient"
    }
}

// region Event payloads

@Serializable
internal data class InterfaceLifecycleEvent(val state: State, val data: Data? = null) {
    @Serializable
    enum class State {
        @SerialName("mounted") MOUNTED,
        @SerialName("ready") READY,
        @SerialName("unmounted") UNMOUNTED,
        @SerialName("error") ERROR,
    }

    @Serializable
    data class Data(val origin: String? = null)
}

@Serializable
internal data class InterfaceActionEvent(
    val action: Action,
    val data: Data? = null,
) {
    @Serializable
    enum class Action {
        @SerialName("close") CLOSE,
        @SerialName("upload") UPLOAD,
        @SerialName("speech") SPEECH,
        @SerialName("select") SELECT,
        @SerialName("download") DOWNLOAD,
    }

    @Serializable
    data class Data(
        val origin: String? = null,
        val state: State? = null,
        val `object`: Object? = null,
        val target: LocalMessage? = null,
        val file: File? = null,
        val pointer: Pointer? = null,
    ) {
        @Serializable
        enum class State {
            @SerialName("record") RECORD,
            @SerialName("cancel") CANCEL,
            @SerialName("send") SEND,
        }

        @Serializable
        enum class Object {
            @SerialName("message") MESSAGE,
        }

        @Serializable data class File(val type: String, val url: String, val name: String)

        @Serializable data class Pointer(val x: Double, val y: Double)
    }
}

/** Emitted when the user taps a button on a picker message injected from native. */
@Serializable
internal data class PickerClickEvent(
    val fingerprint: MessageFingerprint,
    @SerialName("picker_id") val pickerId: PickerId,
    @SerialName("choice_value") val choiceValue: String,
)

@Serializable
internal data class LogEvent(val level: Level, val ns: String, val value: String) {
    @Serializable
    enum class Level {
        @SerialName("error") ERROR,
        @SerialName("warn") WARN,
        @SerialName("info") INFO,
        @SerialName("log") LOG,
        @SerialName("debug") DEBUG,
    }
}

@Serializable
internal data class ScriptErrorEvent(
    val source: Source,
    val message: String,
    val filename: String? = null,
    val line: Int? = null,
    val col: Int? = null,
    val stack: String? = null,
) {
    @Serializable
    enum class Source {
        @SerialName("error") ERROR,
        @SerialName("unhandledrejection") UNHANDLED_REJECTION,
    }
}

// endregion
